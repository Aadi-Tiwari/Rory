"""Backend B - writes TriageDecision and RegulationsCheck objects to Foundry.

Uses the Foundry REST API directly. In production this would use the Foundry
Python SDK, but the SDK requires workspace-specific generated bindings that
aren't available until hour 1 when Person B creates the workspace. For the
hackathon we POST to the Foundry REST endpoints with the PAT from .env.
"""
from __future__ import annotations

import os
import uuid
from typing import Any

import httpx
from dotenv import load_dotenv

from contract.schema import PredictResponse

load_dotenv()

FOUNDRY_WORKSPACE_URL = os.getenv("FOUNDRY_WORKSPACE_URL", "")
FOUNDRY_TOKEN = os.getenv("FOUNDRY_TOKEN", "")
FOUNDRY_ONTOLOGY_RID = os.getenv("FOUNDRY_ONTOLOGY_RID", "")

# Foundry API names (camelCase, auto-generated by Ontology Manager)
# Display names in Foundry UI use "RORY_*" / "RORY *" but the API uses these.
OT_PATIENT = "RoryPatient"
OT_ENCOUNTER = "RoryEncounter"
OT_VITAL_SNAPSHOT = "RoryVitalSnapshot"
OT_TRIAGE_DECISION = "RoryTriageDecision"
OT_REGULATIONS_CHECK = "RoryRegulationsCheck"
OT_PROTOCOL_CITATION = "RoryProtocolCitation"


def _headers() -> dict[str, str]:
    return {
        "Authorization": f"Bearer {FOUNDRY_TOKEN}",
        "Content-Type": "application/json",
    }


def _ontology_url(object_type: str) -> str:
    return (
        f"{FOUNDRY_WORKSPACE_URL}/api/v2/ontologies/{FOUNDRY_ONTOLOGY_RID}"
        f"/objectTypes/{object_type}/objects"
    )


def write_triage_decision(encounter_id: str, response: PredictResponse) -> dict[str, Any]:
    """Create a RoryTriageDecision object in the Foundry Ontology."""
    # Use the interpret_cluster_drift Logic function output when available.
    # For hour 0 we inline the drift logic here; once Person B deploys the
    # Logic function to Foundry, swap this for a function invocation.
    drift_phrase = _interpret_drift_inline(
        response.cluster_drift, response.sepsis_confidence_trend
    )

    reasoning_bullets = [r.bullet for r in response.reasoning]
    if drift_phrase:
        reasoning_bullets.append(drift_phrase)

    payload = {
        "decision_id": f"D_{uuid.uuid4().hex[:8].upper()}",
        "encounter_id": encounter_id,
        # Note: property is triage_class (not class) to avoid reserved-word issues in AIP Logic
        "triage_class": response.recommendation,
        "risk": response.risk,
        "confidence": response.confidence,
        "reasoning": reasoning_bullets,
        "outlier_flag": response.outlier_flag,
        "cluster_drift": response.cluster_drift,
        "drift_alert": response.drift_alert,
        "sepsis_confidence_trend": response.sepsis_confidence_trend,
        "model_version": response.model_version,
    }

    if not FOUNDRY_WORKSPACE_URL:
        # Hour 0 stub: print-only until Foundry workspace exists
        print(f"[STUB] {OT_TRIAGE_DECISION} would be created: {payload}")
        return payload

    with httpx.Client(timeout=10.0) as client:
        resp = client.post(
            _ontology_url(OT_TRIAGE_DECISION), json=payload, headers=_headers()
        )
        resp.raise_for_status()
        return resp.json()


def write_regulations_check(
    encounter_id: str,
    response: PredictResponse,
    patient_mrn: str,
) -> dict[str, Any]:
    """Create a RegulationsCheck object in the Foundry Ontology."""
    has_prior = _patient_has_prior_encounter(patient_mrn)

    reasoning_text = " ".join(r.bullet.lower() for r in response.reasoning)

    payload = {
        "check_id": f"R_{uuid.uuid4().hex[:8].upper()}",
        "encounter_id": encounter_id,
        "vital_signs_recorded": response.completeness >= 0.6,
        "mental_status_assessed": any(
            kw in reasoning_text
            for kw in ("mental status", "confused", "eye contact", "feels weird", "alert")
        ),
        "sepsis_screen_triggered": response.risk >= 0.3,
        "escalation_required": response.recommendation in ("ED", "911"),
        "re_presentation_flag": has_prior,
        "wound_source_documented": any(
            kw in reasoning_text for kw in ("wound", "scrape", "cut", "laceration")
        ),
        "physician_notified": False,
        "discharge_criteria_met": response.recommendation == "HOME",
        "missing_items": _compute_missing_items(response, has_prior),
    }

    if not FOUNDRY_WORKSPACE_URL:
        print(f"[STUB] {OT_REGULATIONS_CHECK} would be created: {payload}")
        return payload

    with httpx.Client(timeout=10.0) as client:
        resp = client.post(
            _ontology_url(OT_REGULATIONS_CHECK), json=payload, headers=_headers()
        )
        resp.raise_for_status()
        return resp.json()


def _interpret_drift_inline(drift: float, trend: list[float]) -> str:
    """Mirror of interpret_cluster_drift Logic function for pre-Foundry operation."""
    if len(trend) < 3:
        return ""
    recent = trend[-3:]
    delta = recent[-1] - recent[0]
    monotonic = all(recent[i] >= recent[i - 1] for i in range(1, len(recent)))
    if drift < -0.05 and monotonic and delta > 0.15:
        return "Patient trajectory accelerating toward septic presentation."
    if drift < -0.02 and delta > 0.08:
        return "Patient drifting toward septic cluster."
    return ""


def _patient_has_prior_encounter(patient_mrn: str) -> bool:
    """Check if the patient has a prior encounter in the Ontology.

    Stubbed to False pre-Foundry. Replace with an ontology query once
    Person B creates the workspace.
    """
    if not FOUNDRY_WORKSPACE_URL:
        return False
    # TODO: real implementation once Foundry SDK is wired
    return False


def _compute_missing_items(response: PredictResponse, has_prior: bool) -> list[str]:
    missing: list[str] = []
    if response.completeness < 1.0:
        missing.append(f"vitals_incomplete ({int(response.completeness * 100)}% captured)")
    if response.recommendation in ("ED", "911"):
        missing.append("physician_notification_pending")
    if has_prior and response.recommendation == "HOME":
        missing.append("re_presentation_requires_physician_review")
    return missing
